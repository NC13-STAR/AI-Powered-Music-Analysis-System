# ============================================================
# BASIC TEXT HELPERS
# ============================================================

def clean_text(value: Any) -> str:

    if value is None:
        return ""

    try:
        if isinstance(
            value,
            float,
        ) and math.isnan(value):

            return ""

    except Exception:
        pass

    text = str(value).strip()

    if (
        text.lower()
        in MISSING_VALUES
    ):
        return ""

    return text


def normalize_key(
    value: Any,
) -> str:

    text = clean_text(
        value
    ).lower()

    text = re.sub(
        r"[^a-z0-9]+",
        "_",
        text,
    )

    return text.strip("_")


# ============================================================
# FLEXIBLE FIELD READER
# ============================================================

def get_field(
    record: Dict[str, Any],
    aliases: List[str],
) -> str:

    normalized = {
        normalize_key(k): v
        for k, v in record.items()
    }

    alias_keys = [
        normalize_key(a)
        for a in aliases
    ]

    # --------------------------------------------------------
    # Exact match
    # --------------------------------------------------------

    for alias in alias_keys:

        if alias in normalized:

            value = clean_text(
                normalized[alias]
            )

            if value:
                return value

    # --------------------------------------------------------
    # Partial match
    # --------------------------------------------------------

    for field_key, value in normalized.items():

        value_text = clean_text(
            value
        )

        if not value_text:
            continue

        for alias in alias_keys:

            if (
                field_key == alias
                or field_key.endswith(
                    "_" + alias
                )
                or alias in field_key
            ):

                return value_text

    return ""


# ============================================================
# METADATA DETECTION
# ============================================================

def is_metadata_text(
    value: str,
) -> bool:

    text = clean_text(
        value
    )

    if not text:
        return True

    lower = text.lower()

    metadata_prefixes = (
        "title:",
        "song:",
        "artist:",
        "singer:",
        "album:",
        "lyrics:",
        "composer:",
        "filename:",
        "duration:",
    )

    if lower.startswith(
        metadata_prefixes
    ):
        return True

    # Known metadata header from this project.
    known_headers = {
        "vande mataram - chandrashekhar vaze",
        "vande mataram - pt. chandrashekhar vaze",
    }

    if lower in known_headers:
        return True

    return False


# ============================================================
# UNICODE LYRIC VALIDATION
# ============================================================

def has_unicode_letter(
    text: str,
) -> bool:

    return any(
        unicodedata.category(ch).startswith("L")
        for ch in text
    )


def strip_outer_punctuation(
    text: str,
) -> str:

    text = text.strip()

    # Remove punctuation/symbols from the beginning.
    while text:

        category = (
            unicodedata.category(
                text[0]
            )
        )

        if (
            category.startswith("P")
            or category.startswith("S")
        ):

            text = text[1:]

        else:
            break

    # Remove punctuation/symbols from the end.
    while text:

        category = (
            unicodedata.category(
                text[-1]
            )
        )

        if (
            category.startswith("P")
            or category.startswith("S")
        ):

            text = text[:-1]

        else:
            break

    return text.strip()


def is_real_lyric_word(
    value: str,
) -> bool:

    """
    Determine whether a token is a real lyric word.

    Rejected:

        ।
        ॥
        |
        ||
        ,
        .
        १
        २
        ३
        123

    Accepted:

        वन्दे
        मातरम्
        bhakti
        कोटि-कोटि-कण्ठ
    """

    text = clean_text(
        value
    )

    if not text:
        return False

    text = strip_outer_punctuation(
        text
    )

    if not text:
        return False

    # A real lyric token must contain at least
    # one Unicode letter.
    return has_unicode_letter(
        text
    )


def clean_lyric_word(
    value: str,
) -> str:

    text = clean_text(
        value
    )

    return strip_outer_punctuation(
        text
    )


# ============================================================
# NORMALIZE ONE ALIGNMENT RECORD
# ============================================================

def normalize_record(
    record: Dict[str, Any],
    index: int,
) -> Optional[Dict[str, Any]]:

    lyric = get_field(
        record,
        [
            "lyric",
            "lyrics",
            "word",
            "lyric_word",
            "text",
            "token",
        ],
    )

    if not lyric:
        return None

    lyric = clean_lyric_word(
        lyric
    )

    # --------------------------------------------------------
    # IMPORTANT:
    # punctuation and numbering are NOT lyrics.
    # --------------------------------------------------------

    if not is_real_lyric_word(
        lyric
    ):
        return None

    if is_metadata_text(
        lyric
    ):
        return None

    # --------------------------------------------------------
    # Indian swara
    # --------------------------------------------------------

    swara = get_field(
        record,
        [
            "indian_swara",
            "indian_swaras",
            "indian_swara_notation",
            "swara",
            "swaras",
            "indian_notation",
            "indian",
        ],
    )

    # --------------------------------------------------------
    # Western note
    # --------------------------------------------------------

    western = get_field(
        record,
        [
            "western_note",
            "western_notes",
            "western_notation",
            "western_note_notation",
            "western",
            "note",
            "notes",
        ],
    )

    # --------------------------------------------------------
    # Line number
    # --------------------------------------------------------

    line_number = get_field(
        record,
        [
            "line_number",
            "line",
            "lyric_line",
            "line_index",
        ],
    )

    # --------------------------------------------------------
    # Word index
    # --------------------------------------------------------

    word_index = get_field(
        record,
        [
            "word_index",
            "word_number",
            "token_index",
        ],
    )

    return {
        "index": index,
        "line_number": line_number or "",
        "word_index": word_index or "",
        "lyric": lyric,
        "indian_swara": (
            swara
            if swara
            else "-"
        ),
        "western_note": (
            western
            if western
            else "-"
        ),
    }


# ============================================================
# NOTATION COVERAGE
# ============================================================

def notation_coverage(
    rows: List[Dict[str, Any]],
) -> int:

    return sum(
        1
        for row in rows
        if (
            row.get(
                "indian_swara",
                "-"
            )
            != "-"
            or
            row.get(
                "western_note",
                "-"
            )
            != "-"
        )
    )


# ============================================================
# JSON ALIGNMENT EXTRACTION
# ============================================================

def extract_direct_alignment_list(
    data: Any,
) -> List[Dict[str, Any]]:

    """
    Phase 13.2 JSON normally contains:

        aligned_words

    This function deliberately looks for that first.

    This prevents the previous problem where the GUI could
    accidentally select the generic 'lyrics' list instead of
    the actual aligned word records.
    """

    if not isinstance(
        data,
        dict,
    ):
        return []

    preferred_keys = (
        "aligned_words",
        "word_notation",
        "word_alignment",
        "alignment",
        "records",
    )

    for wanted in preferred_keys:

        for key_name, value in data.items():

            if (
                normalize_key(
                    key_name
                )
                == wanted
                and isinstance(
                    value,
                    list,
                )
            ):

                if (
                    value
                    and all(
                        isinstance(
                            item,
                            dict,
                        )
                        for item in value
                    )
                ):

                    return value

    return []


# ============================================================
# RECURSIVE JSON SEARCH
# ============================================================

def recursive_dict_lists(
    value: Any,
) -> List[List[Dict[str, Any]]]:

    found = []

    if isinstance(
        value,
        list,
    ):

        if (
            value
            and all(
                isinstance(
                    item,
                    dict,
                )
                for item in value
            )
        ):

            found.append(
                value
            )

        else:

            for item in value:

                found.extend(
                    recursive_dict_lists(
                        item
                    )
                )

    elif isinstance(
        value,
        dict,
    ):

        for child in value.values():

            found.extend(
                recursive_dict_lists(
                    child
                )
            )

    return found


# ============================================================
# SCORE POSSIBLE JSON LIST
# ============================================================

def score_alignment_list(
    rows: List[Dict[str, Any]],
) -> int:

    score = min(
        len(rows),
        500,
    )

    for row in rows[:50]:

        keys = {
            normalize_key(k)
            for k in row.keys()
        }

        if any(
            key_name in keys
            for key_name in (
                "lyric",
                "lyrics",
                "word",
                "lyric_word",
                "text",
                "token",
            )
        ):
            score += 20

        if any(
            key_name in keys
            for key_name in (
                "indian_swara",
                "indian_swaras",
                "swara",
                "swaras",
                "indian_notation",
            )
        ):
            score += 20

        if any(
            key_name in keys
            for key_name in (
                "western_note",
                "western_notes",
                "western",
                "western_notation",
            )
        ):
            score += 20

    return score


# ============================================================
# LOAD JSON
# ============================================================

def load_from_json() -> List[Dict[str, Any]]:

    if not JSON_IN.is_file():
        return []

    print(
        f"Input JSON: {JSON_IN}"
    )

    try:

        data = json.loads(
            JSON_IN.read_text(
                encoding="utf-8"
            )
        )

    except Exception as exc:

        print(
            f"[!] Could not read JSON: {exc}"
        )

        return []

    # First use the known Phase 13.2 alignment list.
    candidates = (
        extract_direct_alignment_list(
            data
        )
    )

    # If that was not found, search recursively.
    if not candidates:

        possible_lists = (
            recursive_dict_lists(
                data
            )
        )

        if possible_lists:

            candidates = max(
                possible_lists,
                key=score_alignment_list,
            )

    if not candidates:
        return []

    rows = []

    for index, raw in enumerate(
        candidates,
        start=1,
    ):

        if not isinstance(
            raw,
            dict,
        ):
            continue

        item = normalize_record(
            raw,
            index,
        )

        if item:
            rows.append(
                item
            )

    return rows


# ============================================================
# LOAD CSV
# ============================================================

def load_from_csv() -> List[Dict[str, Any]]:

    if not CSV_IN.is_file():
        return []

    print(
        f"Input CSV: {CSV_IN}"
    )

    for encoding in (
        "utf-8-sig",
        "utf-8",
        "utf-16",
        "cp1252",
        "latin-1",
    ):

        try:

            with CSV_IN.open(
                "r",
                encoding=encoding,
                newline="",
            ) as handle:

                reader = csv.DictReader(
                    handle
                )

                raw_rows = list(
                    reader
                )

            rows = []

            for index, raw in enumerate(
                raw_rows,
                start=1,
            ):

                item = normalize_record(
                    raw,
                    index,
                )

                if item:
                    rows.append(
                        item
                    )

            return rows

        except UnicodeDecodeError:
            continue

        except Exception as exc:

            print(
                f"[!] CSV read error: {exc}"
            )

            return []

    return []


# ============================================================
# LOAD BEST ALIGNMENT
# ============================================================

def load_alignment() -> List[Dict[str, Any]]:

    """
    Prefer JSON if it contains real notation.

    If JSON accidentally points at the wrong list,
    use the Phase 13.2 word CSV.

    This specifically fixes the old popup problem where
    the lyric column was populated but Indian/Western
    notation showed '-'.
    """

    json_rows = (
        load_from_json()
    )

    csv_rows = (
        load_from_csv()
    )

    json_quality = notation_coverage(
        json_rows
    )

    csv_quality = notation_coverage(
        csv_rows
    )

    # --------------------------------------------------------
    # JSON with notation
    # --------------------------------------------------------

    if (
        json_rows
        and json_quality > 0
    ):

        print(
            f"[✓] Phase 13.2 JSON alignment loaded: "
            f"{len(json_rows)} records"
        )

        print(
            f"    Records containing notation: "
            f"{json_quality}"
        )

        return json_rows

    # --------------------------------------------------------
    # CSV with notation
    # --------------------------------------------------------

    if (
        csv_rows
        and csv_quality > 0
    ):

        print(
            f"[✓] Phase 13.2 word CSV alignment loaded: "
            f"{len(csv_rows)} records"
        )

        print(
            f"    Records containing notation: "
            f"{csv_quality}"
        )

        return csv_rows

    # --------------------------------------------------------
    # Fallback to whichever contains lyrics.
    # --------------------------------------------------------

    if json_rows:

        print(
            "[!] JSON alignment contains lyrics "
            "but no usable notation."
        )

        return json_rows

    if csv_rows:

        print(
            "[!] CSV alignment contains lyrics "
            "but no usable notation."
        )

        return csv_rows

    raise FileNotFoundError(
        "No usable Phase 13.2 alignment was found.\n\n"
        f"Expected:\n"
        f"  {JSON_IN}\n"
        f"  {CSV_IN}"
    )


# ============================================================
# REMOVE DUPLICATE RECORDS
# ============================================================

def remove_duplicate_records(
    rows: List[Dict[str, Any]],
) -> List[Dict[str, Any]]:

    result = []
    seen = set()

    for row in rows:

        identity = (
            str(
                row.get(
                    "line_number",
                    "",
                )
            ),
            str(
                row.get(
                    "word_index",
                    "",
                )
            ),
            row.get(
                "lyric",
                "",
            ),
            row.get(
                "indian_swara",
                "",
            ),
            row.get(
                "western_note",
                "",
            ),
        )

        if identity in seen:
            continue

        seen.add(
            identity
        )

        result.append(
            row
        )

    return result


# ============================================================
# RENUMBER
# ============================================================

def renumber_rows(
    rows: List[Dict[str, Any]],
) -> List[Dict[str, Any]]:

    result = []

    for index, row in enumerate(
        rows,
        start=1,
    ):

        new_row = dict(
            row
        )

        new_row[
            "index"
        ] = index

        result.append(
            new_row
        )

    return result


# ============================================================
# SAVE CLEAN OUTPUT
# ============================================================

def save_outputs(
    rows: List[Dict[str, Any]],
) -> None:

    fields = [
        "index",
        "line_number",
        "word_index",
        "lyric",
        "indian_swara",
        "western_note",
    ]

    with CSV_OUT.open(
        "w",
        encoding="utf-8-sig",
        newline="",
    ) as handle:

        writer = csv.DictWriter(
            handle,
            fieldnames=fields,
        )

        writer.writeheader()

        for row in rows:

            writer.writerow(
                {
                    field: row.get(
                        field,
                        "",
                    )
                    for field in fields
                }
            )

    JSON_OUT.write_text(
        json.dumps(
            {
                "phase": "13.3",
                "description": (
                    "Clean full-song lyric / "
                    "musical notation alignment"
                ),
                "record_count": len(rows),
                "records": rows,
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )

    indian_count = sum(
        1
        for row in rows
        if row.get(
            "indian_swara",
            "-",
        )
        != "-"
    )

    western_count = sum(
        1
        for row in rows
        if row.get(
            "western_note",
            "-",
        )
        != "-"
    )

    summary = [
        "PHASE 13.3 - SUMMARY",
        "=" * 70,
        "",
        f"Complete lyric words displayed : {len(rows)}",
        f"Words with Indian swaras       : {indian_count}",
        f"Words with Western notes       : {western_count}",
        "",
        "Excluded from lyric display:",
        "  - song title / artist metadata",
        "  - standalone punctuation such as |, ||, ।, ॥",
        "  - standalone lyric numbering such as १, २, ३",
        "",
        "Popup format:",
        "  lyric word",
        "  Indian swara",
        "  Western note",
        "",
        "Timing columns are intentionally hidden.",
    ]

    SUMMARY_OUT.write_text(
        "\n".join(summary),
        encoding="utf-8",
    )


