#
#    IS retained.
#
# 6. Popup layout:
#
#       LYRIC WORD
#       Indian Swara
#       Western Note
#
# 7. Start/end/duration are NOT displayed.
#
# 8. Phase 13.3 does not recalculate musical notation.
#    It reads the notation already generated by Phase 13.2.
