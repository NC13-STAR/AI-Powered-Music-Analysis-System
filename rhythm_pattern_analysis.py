def print_rhythm_pattern_results(
    beat_times,
    intervals,
    local_bpm,
    cycle_statistics
):
    """
    Print Phase 8.4 results.
    """

    print(
        "\n" + "-" * 65
    )

    print(
        "RHYTHM PATTERN ANALYSIS RESULTS"
    )

    print(
        "-" * 65
    )

    print(
        f"Total beat events          : "
        f"{len(beat_times)}"
    )

    print(
        f"Mean beat interval         : "
        f"{np.mean(intervals):.4f} sec"
    )

    print(
        f"Median beat interval       : "
        f"{np.median(intervals):.4f} sec"
    )

    print(
        f"Mean local BPM             : "
        f"{np.mean(local_bpm):.2f}"
    )

    print(
        f"Median local BPM           : "
        f"{np.median(local_bpm):.2f}"
    )

    if len(cycle_statistics) > 0:

        print(
            "\nCandidate rhythmic cycles:"
        )

        display_data = (
            cycle_statistics
            .sort_values(
                "autocorrelation_score",
                ascending=False
            )
            .head(10)
        )

        for _, row in display_data.iterrows():

            cycle = int(
                row[
                    "cycle_length_beats"
                ]
            )

            score = float(
                row[
                    "autocorrelation_score"
                ]
            )

            consistency = row[
                "cycle_consistency"
            ]

            if np.isfinite(
                consistency
            ):
                consistency_text = (
                    f"{consistency:.3f}"
                )
            else:
                consistency_text = "N/A"

            print(
                f"{cycle:2d} beats"
                f" | periodicity: "
                f"{score:.3f}"
                f" | consistency: "
                f"{consistency_text}"
            )

    else:

        print(
            "\nNo strong rhythmic cycle candidates "
            "were detected."
        )

    print(
        "\nImportant:"
    )

    print(
        "These cycle lengths are rhythmic candidates only."
    )

    print(
        "Phase 8.4 does NOT assign a final taal."
    )


def save_rhythm_pattern_data(
    beat_times,
    beat_strength,
    normalized_strength,
    strength_class,
    cycle_statistics
):
    """
    Save beat-level and cycle-level results.
    """

    os.makedirs(
        "data/output",
        exist_ok=True
    )

    beat_output = pd.DataFrame(
        {
            "beat_number":
                np.arange(
                    1,
                    len(beat_times) + 1
                ),

            "beat_time_seconds":
                beat_times,

            "beat_strength":
                beat_strength,

            "normalized_beat_strength":
                normalized_strength,

            "strength_class":
                strength_class
        }
    )

    beat_file = (
        "data/output/"
        "rhythm_pattern_analysis.csv"
    )

    beat_output.to_csv(
        beat_file,
        index=False
    )

    print(
        "\nBeat-level rhythm pattern data saved successfully!"
    )

    print(
        f"Saved file: {beat_file}"
    )

    cycle_file = (
        "data/output/"
        "rhythmic_cycle_candidates.csv"
    )

    cycle_statistics.to_csv(
        cycle_file,
        index=False
    )

    print(
        "\nRhythmic cycle candidate data saved successfully!"
    )

    print(
        f"Saved file: {cycle_file}"
    )

    return (
        beat_output,
        cycle_statistics
    )


def analyze_rhythm_pattern(
    audio,
    sample_rate
):
    """
    Main Phase 8.4 function.
    """

    print(
        "\n" + "=" * 70
    )

    print(
        "PHASE 8.4 - RHYTHM PATTERN ANALYSIS"
    )

    print(
        "=" * 70
    )

    print(
        "\nStep 1 - Loading beat timing data..."
    )

    data = load_beat_data()

    print(
        "Beat timing data loaded successfully."
    )

    print(
        f"Total beat events: {len(data)}"
    )

    print(
        "\nStep 2 - Calculating beat-level timing features..."
    )

    (
        beat_times,
        intervals,
        local_bpm
    ) = calculate_beat_features(
        data
    )

    print(
        "Beat-level timing features calculated."
    )

    print(
        "\nStep 3 - Calculating onset strength..."
    )

    (
        onset_envelope,
        onset_times
    ) = calculate_onset_strength(
        audio,
        sample_rate
    )

    print(
        "Onset strength calculated successfully."
    )

    print(
        "\nStep 4 - Measuring rhythmic strength at beat locations..."
    )

    beat_strength = (
        interpolate_onset_strength(
            beat_times,
            onset_envelope,
            onset_times
        )
    )

    (
        normalized_strength,
        strength_class
    ) = calculate_rhythmic_strength(
        beat_strength
    )

    print(
        "Beat strength pattern calculated."
    )

    print(
        "\nStep 5 - Searching for repeated rhythmic cycles..."
    )

    autocorrelation_data = (
        autocorrelation_scores(
            normalized_strength,
            max_cycle_length=32
        )
    )

    print(
        "Rhythmic periodicity analysis completed."
    )

    print(
        "\nStep 6 - Selecting candidate rhythmic cycles..."
    )

    candidate_cycles = (
        detect_candidate_cycles(
            autocorrelation_data,
            minimum_score=0.15
        )
    )

    print(
        f"Candidate cycle lengths detected: "
        f"{len(candidate_cycles)}"
    )

    print(
        "\nStep 7 - Measuring cycle consistency..."
    )

    cycle_statistics = (
        calculate_cycle_statistics(
            normalized_strength,
            candidate_cycles
        )
    )

    print(
        "Cycle consistency analysis completed."
    )

    print_rhythm_pattern_results(
        beat_times,
        intervals,
        local_bpm,
        cycle_statistics
    )

    create_rhythm_pattern_graph(
        beat_times,
        normalized_strength,
        strength_class
    )

    create_cycle_score_graph(
        cycle_statistics
    )

    (
        beat_output,
        cycle_output
    ) = save_rhythm_pattern_data(
        beat_times,
        beat_strength,
        normalized_strength,
        strength_class,
        cycle_statistics
    )

    print(
        "\n" + "=" * 70
    )

    print(
        "PHASE 8.4 COMPLETED SUCCESSFULLY"
    )

    print(
        "=" * 70
    )

    return (
        beat_output,
        cycle_output
    )