import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import librosa


def load_beat_data():
    """
    Load beat timing information generated by Phase 8.1.
    """

    input_file = "data/output/rhythm_analysis.csv"

    if not os.path.exists(input_file):
        raise FileNotFoundError(
            f"Required file not found: {input_file}"
        )

    data = pd.read_csv(input_file)

    if "beat_time_seconds" not in data.columns:
        raise ValueError(
            "rhythm_analysis.csv does not contain "
            "'beat_time_seconds' column."
        )

    data = data.dropna(
        subset=["beat_time_seconds"]
    ).copy()

    data["beat_time_seconds"] = (
        data["beat_time_seconds"]
        .astype(float)
    )

    data = data.sort_values(
        "beat_time_seconds"
    ).reset_index(drop=True)

    return data


def calculate_beat_features(data):
    """
    Calculate beat intervals, local BPM and normalized
    rhythmic timing features.
    """

    beat_times = (
        data["beat_time_seconds"]
        .to_numpy(dtype=float)
    )

    if len(beat_times) < 3:
        raise ValueError(
            "Not enough beat events for rhythm pattern analysis."
        )

    intervals = np.diff(beat_times)

    valid_intervals = (
        np.isfinite(intervals) &
        (intervals > 0)
    )

    intervals_clean = intervals[valid_intervals]

    local_bpm = 60.0 / intervals_clean

    return beat_times, intervals_clean, local_bpm


def calculate_onset_strength(audio, sample_rate):
    """
    Calculate onset strength at beat locations.
    """

    onset_envelope = librosa.onset.onset_strength(
        y=audio,
        sr=sample_rate
    )

    onset_times = librosa.times_like(
        onset_envelope,
        sr=sample_rate
    )

    return onset_envelope, onset_times


def interpolate_onset_strength(
    beat_times,
    onset_envelope,
    onset_times
):
    """
    Estimate onset strength at each detected beat time.
    """

    beat_strength = np.interp(
        beat_times,
        onset_times,
        onset_envelope
    )

    return beat_strength


def normalize_values(values):
    """
    Normalize values to approximately 0-1.
    """

    values = np.asarray(
        values,
        dtype=float
    )

    minimum = np.nanmin(values)
    maximum = np.nanmax(values)

    if maximum - minimum < 1e-12:
        return np.zeros_like(values)

    return (
        (values - minimum) /
        (maximum - minimum)
    )


def calculate_rhythmic_strength(
    beat_strength
):
    """
    Normalize beat strength and classify beats
    into relative strong/weak categories.
    """

    normalized = normalize_values(
        beat_strength
    )

    median_strength = np.median(
        normalized
    )

    strength_class = np.where(
        normalized >= median_strength,
        "Strong",
        "Weak"
    )

    return normalized, strength_class


def autocorrelation_scores(
    beat_strength,
    max_cycle_length=32
):
    """
    Estimate periodicity of beat-strength patterns.

    A high score means that the rhythmic-strength pattern
    resembles itself after that many beats.
    """

    values = np.asarray(
        beat_strength,
        dtype=float
    )

    values = values - np.mean(values)

    denominator = np.sum(values ** 2)

    if denominator <= 1e-12:
        return pd.DataFrame(
            columns=[
                "cycle_length_beats",
                "autocorrelation_score"
            ]
        )

    maximum_cycle = min(
        max_cycle_length,
        len(values) // 3
    )

    results = []

    for cycle_length in range(
        2,
        maximum_cycle + 1
    ):

        first = values[:-cycle_length]
        second = values[cycle_length:]

        if len(first) < 2:
            continue

        numerator = np.sum(
            first * second
        )

        denominator_local = np.sqrt(
            np.sum(first ** 2) *
            np.sum(second ** 2)
        )

        if denominator_local <= 1e-12:
            score = 0.0
        else:
            score = (
                numerator /
                denominator_local
            )

        results.append(
            {
                "cycle_length_beats": cycle_length,
                "autocorrelation_score": score
            }
        )

    return pd.DataFrame(results)


def detect_candidate_cycles(
    autocorrelation_data,
    minimum_score=0.15
):
    """
    Select rhythmic cycle lengths with positive
    periodicity evidence.

    This is only candidate detection.
    It does NOT identify the final taal.
    """

    if len(autocorrelation_data) == 0:
        return pd.DataFrame()

    candidates = (
        autocorrelation_data[
            autocorrelation_data[
                "autocorrelation_score"
            ] >= minimum_score
        ]
        .copy()
    )

    candidates = candidates.sort_values(
        "autocorrelation_score",
        ascending=False
    ).reset_index(drop=True)

    return candidates


def analyze_cycle_consistency(
    beat_strength,
    cycle_length
):
    """
    Measure how consistently a candidate cycle repeats.
    """

    values = np.asarray(
        beat_strength,
        dtype=float
    )

    number_of_complete_cycles = (
        len(values) // cycle_length
    )

    if number_of_complete_cycles < 2:
        return np.nan

    usable_length = (
        number_of_complete_cycles *
        cycle_length
    )

    reshaped = values[
        :usable_length
    ].reshape(
        number_of_complete_cycles,
        cycle_length
    )

    mean_pattern = np.mean(
        reshaped,
        axis=0
    )

    correlations = []

    for row in reshaped:

        if (
            np.std(row) < 1e-12 or
            np.std(mean_pattern) < 1e-12
        ):
            continue

        correlation = np.corrcoef(
            row,
            mean_pattern
        )[0, 1]

        if np.isfinite(correlation):
            correlations.append(
                correlation
            )

    if not correlations:
        return np.nan

    return float(
        np.mean(correlations)
    )


def calculate_cycle_statistics(
    beat_strength,
    candidate_cycles
):
    """
    Calculate repeatability and consistency
    for candidate rhythmic cycles.
    """

    results = []

    for _, row in candidate_cycles.iterrows():

        cycle_length = int(
            row["cycle_length_beats"]
        )

        autocorrelation = float(
            row["autocorrelation_score"]
        )

        consistency = (
            analyze_cycle_consistency(
                beat_strength,
                cycle_length
            )
        )

        results.append(
            {
                "cycle_length_beats":
                    cycle_length,

                "autocorrelation_score":
                    autocorrelation,

                "cycle_consistency":
                    consistency
            }
        )

    return pd.DataFrame(results)


def create_rhythm_pattern_graph(
    beat_times,
    normalized_strength,
    strength_class
):
    """
    Create beat-strength visualization.
    """

    os.makedirs(
        "graphs",
        exist_ok=True
    )

    plt.figure(
        figsize=(16, 6)
    )

    colors = np.where(
        strength_class == "Strong",
        "black",
        "gray"
    )

    plt.scatter(
        beat_times,
        normalized_strength,
        s=28,
        c=colors
    )

    plt.plot(
        beat_times,
        normalized_strength,
        linewidth=1,
        alpha=0.5
    )

    plt.xlabel(
        "Time (seconds)"
    )

    plt.ylabel(
        "Normalized Beat Strength"
    )

    plt.title(
        "Phase 8.4 - Rhythmic Beat Strength Pattern"
    )

    plt.grid(
        True,
        alpha=0.3
    )

    plt.tight_layout()

    graph_path = (
        "graphs/"
        "rhythm_pattern_strength.png"
    )

    plt.savefig(
        graph_path,
        dpi=300
    )

    plt.close()

    print(
        "\nRhythm pattern strength graph saved successfully!"
    )

    print(
        f"Saved graph: {graph_path}"
    )


